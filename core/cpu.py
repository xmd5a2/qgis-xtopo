"""Число воркеров для параллельной работы, нагружающей процессор.

На машинах с разным числом ядер нельзя опираться на жёсткие «4» или «8»:
на четырёх ядрах восемь потоков мешают друг другу, а на шестнадцати
четыре не используют половину.  Для CPU-задач берём три четверти
логических ядер: остаётся запас системе и интерфейсу QGIS.
"""

import os

WORKER_RATIO = 0.75


def cpu_workers(limit=None):
    """Три четверти логических ядер, но не меньше одного.

    ``limit`` — дополнительный потолок для задач, где больше воркеров
    по замерам не помогает (например, потоки проверки пиков).
    """
    cores = os.cpu_count() or 1
    workers = max(1, int(cores * WORKER_RATIO))
    if limit is not None:
        workers = min(workers, max(1, int(limit)))
    return workers
